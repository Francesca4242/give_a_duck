// Bundles everything in ./public into src/static.gen.js so the Worker can serve the app itself.
// Runs automatically before `wrangler dev` / `wrangler deploy` (see "build" in wrangler.jsonc).
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname } from "node:path";
import { createHash } from "node:crypto";

const ROOT = new URL("../public/", import.meta.url).pathname;
const TYPES = {
  ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".json": "application/json", ".webmanifest": "application/manifest+json", ".svg": "image/svg+xml",
  ".png": "image/png", ".ico": "image/x-icon", ".txt": "text/plain; charset=utf-8",
};
const TEXT = new Set([".html", ".css", ".js", ".json", ".webmanifest", ".svg", ".txt"]);

const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    const rel = "/" + relative(ROOT, p).split("\\").join("/");
    const ext = extname(name);
    if (!TYPES[ext]) continue; // skips _headers etc.
    const buf = readFileSync(p);
    files[rel] = { type: TYPES[ext], text: TEXT.has(ext), body: TEXT.has(ext) ? buf.toString("utf8") : buf.toString("base64"), etag: '"' + createHash("sha1").update(buf).digest("hex").slice(0, 16) + '"' };
  }
})(ROOT);

writeFileSync(new URL("../src/static.gen.js", import.meta.url), "// Generated by scripts/build-static.mjs — do not edit.\nexport default " + JSON.stringify(files) + ";\n");
console.log(`bundled ${Object.keys(files).length} files from public/`);
